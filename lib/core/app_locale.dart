const supportedLanguageCodes = ['es', 'en', 'it', 'de', 'id'];

final appLocaleProvider = StateNotifierProvider<AppLocaleController, String>(
  (ref) => AppLocaleController(),
);

class AppLocaleController extends StateNotifier<String> {
  AppLocaleController() : super(_systemLanguage()) {
    _load();
  }

  static String _systemLanguage() {
    final code = PlatformDispatcher.instance.locale.languageCode.toLowerCase();
    return supportedLanguageCodes.contains(code) ? code : 'es';
  }

  Future<void> _load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString('app_locale');
    if (saved != null && supportedLanguageCodes.contains(saved)) state = saved;
  }

  Future<void> setLanguage(String code) async {
    if (!supportedLanguageCodes.contains(code)) return;
    state = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_locale', code);
  }
}

